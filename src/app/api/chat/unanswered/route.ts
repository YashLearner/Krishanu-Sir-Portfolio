import { NextResponse } from "next/server";

import { findAnswer } from "@/lib/findAnswer";
import { createSupabaseAdminClient } from "@/lib/supabaseAdmin";

const MAX_QUESTION_LENGTH = 500;

export async function POST(request: Request) {
    try {
        // Parse incoming request.
        let body: unknown;

        try {
            body = await request.json();
        } catch {
            return NextResponse.json(
                { error: "Invalid request body." },
                { status: 400 }
            );
        }

        // Validate question.
        if (
            typeof body !== "object" ||
            body === null ||
            !("question" in body) ||
            typeof body.question !== "string"
        ) {
            return NextResponse.json(
                { error: "Question is required." },
                { status: 400 }
            );
        }

        const question = body.question.trim();

        if (
            !question ||
            question.length > MAX_QUESTION_LENGTH
        ) {
            return NextResponse.json(
                { error: "Invalid question." },
                { status: 400 }
            );
        }

        // Do not save questions that already have an answer.
        if (findAnswer(question) !== null) {
            return NextResponse.json(
                {
                    success: true,
                    saved: false,
                },
                { status: 200 }
            );
        }

        // Connect to Supabase.
        const supabase = createSupabaseAdminClient();

        // Save only the question.
        // UUID and created_at are generated by PostgreSQL.
        const { error } = await supabase
            .from("unanswered_questions")
            .insert({
                question,
            });

        if (error) {
            console.error("Supabase insert error:", error);

            return NextResponse.json(
                { error: "Failed to save question." },
                { status: 500 }
            );
        }

        return NextResponse.json(
            {
                success: true,
                saved: true,
            },
            { status: 201 }
        );

    } catch (error) {
        console.error("Unanswered question API error:", error);

        return NextResponse.json(
            { error: "Internal server error." },
            { status: 500 }
        );
    }
}